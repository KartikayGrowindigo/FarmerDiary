-- CFP-style crop assessments (admin only). Run after 20261110000000_init.sql.
--
--   assessments             one row per assessment: metadata, CFP-shaped inputs (jsonb), per-section notes
--                           (separate jsonb, never part of inputs), derived section statuses, soft delete.
--   assessment_submissions  immutable snapshot of the inputs and notes each time an assessment is submitted.
--   assessment_events       audit trail written by triggers (created, status changes, deleted, restored).
--   assessment_results      for the calculation engine added later; nothing writes to it yet.
--
-- Only admins (staff.is_admin) can read or write any of these tables; everyone else sees nothing.
-- IDs are text and generated by the app so assessments created offline keep their ID.

create table public.assessments (
  id text primary key,
  display_id text not null unique,
  name text not null check (length(trim(name)) > 0),
  farmer_id text not null references public.farmers (id) on delete restrict,
  plot_ids text[] not null default '{}',
  pathway text not null check (pathway in ('annual_crops', 'paddy_rice', 'potato')),
  crop_type text,
  assessment_year integer,
  schema_version text not null,
  status text not null default 'in_progress' check (status in ('in_progress', 'submitted', 'edit_in_progress')),
  calculation_status text not null default 'not_configured' check (calculation_status in ('not_configured', 'pending', 'calculated', 'failed')),
  inputs jsonb not null default '{}'::jsonb,
  notes jsonb not null default '{}'::jsonb,
  section_status jsonb not null default '{}'::jsonb,
  progress numeric(5, 2) not null default 0,
  prefill jsonb not null default '{}'::jsonb,
  revision integer not null default 0,
  duplicated_from text references public.assessments (id) on delete set null,
  submitted_at timestamptz,
  submitted_by uuid references public.staff (id) on delete set null,
  deleted_at timestamptz,
  created_by uuid references public.staff (id) on delete set null,
  updated_by uuid references public.staff (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint inputs_is_object check (jsonb_typeof(inputs) = 'object'),
  constraint notes_is_object check (jsonb_typeof(notes) = 'object')
);
create index assessments_farmer_idx on public.assessments (farmer_id);
create index assessments_status_idx on public.assessments (status) where deleted_at is null;

create table public.assessment_submissions (
  id text primary key,
  assessment_id text not null references public.assessments (id) on delete cascade,
  revision integer not null,
  schema_version text not null,
  snapshot jsonb not null,
  submitted_by uuid references public.staff (id) on delete set null,
  submitted_at timestamptz not null default now(),
  unique (assessment_id, revision)
);

create table public.assessment_events (
  id bigint generated always as identity primary key,
  assessment_id text not null references public.assessments (id) on delete cascade,
  event text not null,
  detail jsonb,
  actor uuid references public.staff (id) on delete set null,
  at timestamptz not null default now()
);
create index assessment_events_assessment_idx on public.assessment_events (assessment_id, at);

create table public.assessment_results (
  id bigint generated always as identity primary key,
  assessment_id text not null references public.assessments (id) on delete cascade,
  revision integer not null,
  engine text not null,
  engine_version text not null,
  status text not null check (status in ('calculated', 'failed')),
  results jsonb,
  error text,
  calculated_at timestamptz not null default now()
);
create index assessment_results_assessment_idx on public.assessment_results (assessment_id, revision);

-- ---------- Bookkeeping: who and when come from the session, not from the app ----------

create function public.stamp_assessment() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
  else
    new.created_by := old.created_by;
    new.created_at := old.created_at;
  end if;
  if new.submitted_at is distinct from (case when tg_op = 'UPDATE' then old.submitted_at end) then
    new.submitted_by := auth.uid();
  elsif tg_op = 'UPDATE' then
    new.submitted_by := old.submitted_by;
  end if;
  return new;
end $$;
create trigger assessments_stamp before insert or update on public.assessments for each row execute function public.stamp_assessment();

create function public.stamp_submission() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.submitted_by := auth.uid();
  return new;
end $$;
create trigger assessment_submissions_stamp before insert on public.assessment_submissions for each row execute function public.stamp_submission();

-- Submissions are a history: no edits.
create function public.forbid_change() returns trigger
language plpgsql set search_path = '' as $$
begin
  raise exception 'Submitted snapshots cannot be changed';
end $$;
create trigger assessment_submissions_frozen before update on public.assessment_submissions for each row execute function public.forbid_change();

create function public.log_assessment_event() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    insert into public.assessment_events (assessment_id, event, detail, actor)
    values (new.id, case when new.duplicated_from is null then 'created' else 'duplicated' end,
            jsonb_build_object('name', new.name, 'pathway', new.pathway, 'duplicated_from', new.duplicated_from), auth.uid());
  else
    if new.status is distinct from old.status then
      insert into public.assessment_events (assessment_id, event, detail, actor)
      values (new.id, 'status_changed', jsonb_build_object('from', old.status, 'to', new.status, 'revision', new.revision), auth.uid());
    end if;
    if new.deleted_at is not null and old.deleted_at is null then
      insert into public.assessment_events (assessment_id, event, actor) values (new.id, 'deleted', auth.uid());
    elsif new.deleted_at is null and old.deleted_at is not null then
      insert into public.assessment_events (assessment_id, event, actor) values (new.id, 'restored', auth.uid());
    end if;
    if new.name is distinct from old.name then
      insert into public.assessment_events (assessment_id, event, detail, actor)
      values (new.id, 'renamed', jsonb_build_object('from', old.name, 'to', new.name), auth.uid());
    end if;
  end if;
  return null;
end $$;
create trigger assessments_audit after insert or update on public.assessments for each row execute function public.log_assessment_event();
revoke execute on function public.log_assessment_event() from public, anon, authenticated;

-- ---------- Row level security: admins only ----------

alter table public.assessments enable row level security;
alter table public.assessment_submissions enable row level security;
alter table public.assessment_events enable row level security;
alter table public.assessment_results enable row level security;

create policy assessments_admin on public.assessments for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

create policy submissions_admin_read on public.assessment_submissions for select to authenticated
  using (public.is_admin());
create policy submissions_admin_insert on public.assessment_submissions for insert to authenticated
  with check (public.is_admin());

create policy events_admin_read on public.assessment_events for select to authenticated
  using (public.is_admin());

create policy results_admin on public.assessment_results for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

revoke all on public.assessments, public.assessment_submissions, public.assessment_events, public.assessment_results from anon;
